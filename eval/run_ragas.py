"""RAGAS evaluation: ask the running service every question in eval/questions.jsonl and score the answers.

    uv run --group eval python eval/run_ragas.py     # needs the service running (RAG_URL, default localhost:8002)

Metrics (each 0..1, higher is better):
- faithfulness: is every claim in the answer supported by the retrieved chunks? (catches made-up answers)
- answer_relevancy: does the answer address the question?
- context_precision: are the chunks that matter ranked above the ones that don't?
- context_recall: did retrieval find everything the reference answer needs?

An LLM judges each metric (EVAL_LLM_MODEL). Results go to eval/results.md.
"""

import asyncio
import json
import os
from datetime import date
from pathlib import Path

import httpx
from openai import AsyncOpenAI
from ragas.embeddings import embedding_factory
from ragas.llms import llm_factory
from ragas.metrics.collections import AnswerRelevancy, ContextPrecisionWithReference, ContextRecall, Faithfulness

from src.settings import Settings

HERE = Path(__file__).parent
RAG_URL = os.getenv("RAG_URL", "http://localhost:8002")
METRICS = ["faithfulness", "answer_relevancy", "context_precision", "context_recall"]


async def score(metric, **inputs) -> float:
    """Run one metric, waiting out the free tier's per-minute limit (HTTP 429) when it is hit."""
    for _ in range(6):
        try:
            return (await metric.ascore(**inputs)).value
        except Exception as exc:
            if "429" not in str(exc):
                raise
            await asyncio.sleep(30)
    raise RuntimeError("still rate-limited after 3 minutes")


async def main() -> None:
    settings = Settings()
    client = AsyncOpenAI(api_key=settings.llm_api_key, base_url=settings.llm_base_url, max_retries=0)
    llm = llm_factory(settings.eval_llm_model, provider="openai", client=client)
    embeddings = embedding_factory("openai", model=settings.embedding_model, client=client)
    faithfulness = Faithfulness(llm=llm)
    relevancy = AnswerRelevancy(llm=llm, embeddings=embeddings, strictness=1)
    precision = ContextPrecisionWithReference(llm=llm)
    recall = ContextRecall(llm=llm)

    lines = (HERE / "questions.jsonl").read_text().splitlines()
    questions = [json.loads(line) for line in lines if line.strip()]
    rows = []
    async with httpx.AsyncClient(timeout=300) as http:
        for number, item in enumerate(questions, start=1):
            question, reference = item["question"], item["reference"]
            response = await http.post(f"{RAG_URL}/ask", json={"question": question})
            response.raise_for_status()
            answer = response.json()["answer"]
            contexts = [chunk["content"] for chunk in response.json()["chunks"]]

            row = {"question": question, "answer_relevancy": await score(relevancy, user_input=question, response=answer)}
            if contexts:
                row["faithfulness"] = await score(faithfulness, user_input=question, response=answer, retrieved_contexts=contexts)
                row["context_precision"] = await score(precision, user_input=question, reference=reference, retrieved_contexts=contexts)
                row["context_recall"] = await score(recall, user_input=question, retrieved_contexts=contexts, reference=reference)
            else:  # nothing retrieved: nothing to be faithful to, and nothing relevant found
                row.update(faithfulness=0.0, context_precision=0.0, context_recall=0.0)
            rows.append(row)
            print(f"[{number}/{len(questions)}] " + "  ".join(f"{m}={row[m]:.2f}" for m in METRICS) + f"  {question}")

    averages = {m: sum(row[m] for row in rows) / len(rows) for m in METRICS}
    report = [
        f"# RAGAS results ({date.today()})",
        "",
        f"{len(rows)} questions from `eval/questions.jsonl`, judged by `{settings.eval_llm_model}`. "
        "Generated by `eval/run_ragas.py`; don't edit by hand.",
        "",
        "| Metric | Average |",
        "|---|---|",
        *[f"| {m} | {averages[m]:.2f} |" for m in METRICS],
        "",
        "| Question | " + " | ".join(METRICS) + " |",
        "|---|" + "---|" * len(METRICS),
        *["| " + row["question"] + " | " + " | ".join(f"{row[m]:.2f}" for m in METRICS) + " |" for row in rows],
    ]
    (HERE / "results.md").write_text("\n".join(report) + "\n")
    print("\n".join(f"{m}: {averages[m]:.2f}" for m in METRICS))


if __name__ == "__main__":
    asyncio.run(main())
